/* eslint-disable @typescript-eslint/explicit-function-return-type */
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { basename, join } from 'node:path'
import { fileURLToPath } from 'node:url'

export const AUR_PACKAGE_NAME = 'streamdeck-deej-bin'
const UPSTREAM_NAME = 'streamdeck-deej'
const REPOSITORY_URL = 'https://github.com/lachaux-remi/StreamDeckDeeJ-App'
const MAINTAINER = 'Rémi Lachaux <contact@remi-lachaux.fr>'

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex')
}

function readPackageMember(packagePath, member) {
  return execFileSync('tar', ['-xOJf', packagePath, member], {
    encoding: 'utf8',
    maxBuffer: 1024 * 1024
  })
}

// .PKGINFO is "key = value" lines; fpm may wrap a value onto an indented line.
export function parsePackageInfo(text) {
  const entries = []
  for (const line of text.split('\n')) {
    if (line.startsWith('#') || line.trim() === '') {
      continue
    }
    if (/^\s/.test(line) && entries.length > 0) {
      const last = entries[entries.length - 1]
      last[1] = `${last[1]} ${line.trim()}`.trim()
      continue
    }
    const separator = line.indexOf(' = ')
    if (separator === -1) {
      const key = line.replace(/\s*=\s*$/, '')
      entries.push([key, ''])
    } else {
      entries.push([line.slice(0, separator), line.slice(separator + 3).trim()])
    }
  }
  const info = { depends: [] }
  for (const [key, value] of entries) {
    if (key === 'depend') {
      info.depends.push(value)
    } else {
      info[key] = value
    }
  }
  return info
}

function shellWord(value) {
  assert.match(value, /^[\w@.+:/=<>-]+$/, `Unsafe PKGBUILD value: ${value}`)
  return value
}

function quoted(value) {
  assert.ok(!/['\n\\]/.test(value), `Unsafe PKGBUILD string: ${value}`)
  return `'${value}'`
}

export function renderPkgbuild({ version, description, depends, packageSha256, licenseSha256 }) {
  shellWord(version)
  return `# Maintainer: ${MAINTAINER}
# Generated by scripts/prepare-aur-package.mjs from the official release package.

pkgname=${AUR_PACKAGE_NAME}
_pkgname=${UPSTREAM_NAME}
pkgver=${version}
pkgrel=1
pkgdesc=${quoted(description)}
arch=('x86_64')
url=${quoted(REPOSITORY_URL)}
license=('MIT')
depends=(${depends.map((name) => quoted(shellWord(name))).join(' ')})
provides=("$_pkgname=$pkgver")
conflicts=("$_pkgname")
options=('!strip' '!debug')
install="$pkgname.install"
source=("$_pkgname-$pkgver.pkg.tar.xz::$url/releases/download/v$pkgver/$_pkgname-$pkgver.pkg.tar.xz"
        "LICENSE-$pkgver::https://raw.githubusercontent.com/lachaux-remi/StreamDeckDeeJ-App/v$pkgver/LICENSE")
noextract=("$_pkgname-$pkgver.pkg.tar.xz")
sha256sums=('${shellWord(packageSha256)}'
            '${shellWord(licenseSha256)}')

package() {
  bsdtar -xpf "$srcdir/$_pkgname-$pkgver.pkg.tar.xz" -C "$pkgdir" \\
    --exclude .PKGINFO --exclude .MTREE --exclude .INSTALL --exclude .BUILDINFO
  install -Dm644 "$srcdir/LICENSE-$pkgver" "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
}
`
}

// Reuse the official package scriptlets so the udev rule, binary link and
// AppArmor handling stay identical. Packages built before post_upgrade was
// generated (up to 4.2.0) only had post_install, so run it on upgrade too.
export function renderInstallScript(officialInstall) {
  assert.match(officialInstall, /^post_install\(\) \{/m, 'Missing post_install in .INSTALL')
  assert.match(officialInstall, /^post_remove\(\) \{/m, 'Missing post_remove in .INSTALL')
  if (/^post_upgrade\(\) \{/m.test(officialInstall)) {
    return `${officialInstall.trimEnd()}\n`
  }
  return `${officialInstall.trimEnd()}
post_upgrade() {
  post_install
}
`
}

export async function prepareAurPackage(packagePath, version, licensePath, outputDirectory) {
  assert.equal(basename(packagePath), `${UPSTREAM_NAME}-${version}.pkg.tar.xz`)
  const info = parsePackageInfo(readPackageMember(packagePath, '.PKGINFO'))
  assert.equal(info.pkgname, UPSTREAM_NAME)
  assert.equal(info.pkgver, `${version}-1`)
  assert.equal(info.arch, 'x86_64')
  assert.ok(info.depends.length > 0, 'Official package declares no dependencies')

  await mkdir(outputDirectory, { recursive: true })
  await writeFile(
    join(outputDirectory, 'PKGBUILD'),
    renderPkgbuild({
      version,
      description: info.pkgdesc,
      depends: info.depends,
      packageSha256: sha256(await readFile(packagePath)),
      licenseSha256: sha256(await readFile(licensePath))
    })
  )
  await writeFile(
    join(outputDirectory, `${AUR_PACKAGE_NAME}.install`),
    renderInstallScript(readPackageMember(packagePath, '.INSTALL'))
  )
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [packagePath, version, licensePath, outputDirectory] = process.argv.slice(2)
  if (!packagePath || !version || !licensePath || !outputDirectory) {
    throw new Error(
      'Usage: prepare-aur-package.mjs <package.pkg.tar.xz> <version> <LICENSE> <output-directory>'
    )
  }
  await prepareAurPackage(packagePath, version, licensePath, outputDirectory)
  console.log(`Prepared ${AUR_PACKAGE_NAME} ${version} in ${outputDirectory}`)
}
